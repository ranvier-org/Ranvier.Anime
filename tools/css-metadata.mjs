import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceIndex = args.indexOf('--source');
const source = sourceIndex < 0 ? process.env.RANVIER_WEBKIT_SOURCE || 'C:/wk/src' : args[sourceIndex + 1];
const remaining = args.filter((_, i) => sourceIndex < 0 || i !== sourceIndex && i !== sourceIndex + 1);
if (!source || remaining.some(arg => arg !== '--check')) throw new Error('Usage: css-metadata.mjs [--source <WebKit checkout>] [--check]');
const commit = 'b95c91b1c0ee43cc86d25ff7af73038f67a88e04';
const metadataPath = 'Source/WebCore/css/CSSProperties.json';
const input = execFileSync('rtk', ['proxy', 'git', '-C', source, 'show', commit + ':' + metadataPath], { maxBuffer: 4 * 1024 * 1024 });
const metadata = JSON.parse(input);
const variants = value => Array.isArray(value) ? value.flatMap(variants) : [value];
const codegens = value => variants(value).flatMap(value => variants(value['codegen-properties'] || {}));
const names = values => [...new Set(values.map(value => typeof value === 'string' ? value : value.value))];
const properties = new Map(Object.entries(metadata.properties).map(([name, value]) => [name, {
  longhands: names(codegens(value).flatMap(value => value.longhands || [])),
  aliases: names(codegens(value).flatMap(value => value.aliases || [])),
}]));
function expand(name, visiting = []) {
  if (visiting.includes(name)) throw new Error('Cyclic shorthand: ' + name);
  const value = properties.get(name);
  if (!value) throw new Error('Unknown longhand: ' + name);
  if (name === 'all') return [...properties.keys()].filter(name => name !== 'all' && name !== 'direction' && name !== 'unicode-bidi' && !properties.get(name).longhands.length);
  if (!value.longhands.length || value.longhands.length === 1 && value.longhands[0] === name) return [name];
  return [...new Set(value.longhands.flatMap(leaf => expand(leaf, [...visiting, name])))];
}
const expansions = new Map();
function add(name, leaves) {
  if (expansions.has(name) && JSON.stringify(expansions.get(name)) !== JSON.stringify(leaves)) throw new Error('Conflicting alias: ' + name);
  expansions.set(name, leaves);
}
for (const [name, value] of properties) {
  const leaves = expand(name);
  if (value.longhands.length) add(name, leaves);
  for (const alias of value.aliases) add(alias, leaves);
}
const groups = new Map();
for (const [name, value] of Object.entries(metadata.properties)) {
  for (const codegen of codegens(value)) {
    const group = codegen['logical-property-group'];
    if (!group) continue;
    if (!groups.has(group.name)) groups.set(group.name, []);
    groups.get(group.name).push([name, group.resolver]);
  }
}
const related = new Map();
const logical = resolver => /inline|block|start|end/.test(resolver);
for (const group of groups.values()) {
  for (const [name, resolver] of group) related.set(name, [...new Set(group.filter(([, other]) => logical(other) !== logical(resolver)).map(([name]) => name))]);
}
const fsArray = values => '[|' + values.map(JSON.stringify).join(';') + '|]';
const rows = values => [...values].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([name, values]) => '            ' + JSON.stringify(name) + ',' + fsArray(values)).join('\n');
const output = [
  'namespace Ranvier.Anime', '', 'open System.Collections.Frozen', '',
  '// Generated by tools/css-metadata.mjs from WebKit ' + commit + '; see THIRD-PARTY-NOTICES.md.', '',
  '/// <summary>Matched WebCore shorthand expansion and logical counterpart names for scoped inline snapshots.</summary>',
  'module internal CssPropertyMetadata =',
  '    let private expansions =', '        dict [', rows(expansions), '        ]',
  '        |> fun values -> values.ToFrozenDictionary(System.StringComparer.Ordinal)',
  '    let private related =', '        dict [', rows(related), '        ]',
  '        |> fun values -> values.ToFrozenDictionary(System.StringComparer.Ordinal)',
  '    /// <summary>Canonical affected longhands; preserves case-sensitive custom property names.</summary>',
  '    let leafNames (name:string) =',
  '        if name.StartsWith("--",System.StringComparison.Ordinal) then [|name|]',
  '        else',
  '            let name=name.ToLowerInvariant()',
  '            match expansions.TryGetValue name with',
  '            | true,values -> Array.copy values',
  '            | _ -> [|name|]',
  '    /// <summary>Opposite logical mappings whose current values must retain precedence around restored longhands.</summary>',
  '    let counterparts (names:string array) =',
  '        names |> Array.collect(fun name ->',
  '            match related.TryGetValue name with',
  '            | true,values -> values',
  '            | _ -> [||]) |> Array.distinct', '',
].join('\n');
const hash = value => createHash('sha256').update(value).digest('hex');
const receipt = JSON.stringify({
  webkitCommit: commit, metadataPath, metadataSha256: hash(input), generatedSha256: hash(output),
  propertyCount: properties.size, shorthandCount: [...properties.values()].filter(value => value.longhands.length).length,
  aliasCount: [...properties.values()].reduce((count, value) => count + value.aliases.length, 0),
  expansionCount: expansions.size, logicalGroupCount: groups.size,
}, null, 2) + '\n';
const root = fileURLToPath(new URL('../', import.meta.url));
for (const [relative, content] of [
  ['src/Ranvier.Anime/CssPropertyMetadata.fs', output],
  ['tests/reference/css-metadata.json', receipt],
]) {
  const target = path.join(root, relative);
  if (check) {
    if (readFileSync(target, 'utf8') !== content) throw new Error('Stale generated CSS metadata: ' + relative);
  } else writeFileSync(target, content);
}
console.log((check ? 'Verified' : 'Generated') + ' WebKit CSS metadata: ' + expansions.size + ' expansions, ' + groups.size + ' logical groups; SHA256 ' + hash(input));
